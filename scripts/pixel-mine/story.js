// The contract after which each beat plays: the chapters end on 10, 20, 30, 40.
export var STORY_AT = { 0: 0, 1: 1, 4: 2, 7: 3, 10: 4, 14: 5, 17: 6, 19: 7, 20: 8, 25: 9, 30: 10, 35: 11, 40: 12 };

// The lines heard after contract `contract` as "voice: line" pairs, or [] when
// the radio is silent after it.
export function storyLines(contract) {
  var beat = STORY_AT[contract];
  return (beat === undefined ? [] : STORY[beat] || []).map(function (entry) { return { voice: VOICES[entry[0]], text: entry[1] }; });
}

